const { withAppDelegate } = require('@expo/config-plugins');

/**
 * Plugin local para inyectar FirebaseApp.configure() en el AppDelegate
 * basado en escenas del SDK 58. Debe ejecutarse DESPUÉS del plugin oficial
 * de @react-native-firebase/app.
 */
const withFirebaseAppDelegate = (config) => {
  return withAppDelegate(config, (config) => {
    if (config.modResults.language === 'swift') {
      let contents = config.modResults.contents;

      // 1. Asegurar import FirebaseCore si el plugin oficial no lo añadió
      if (!contents.includes('import FirebaseCore')) {
        contents = contents.replace(
          /^(import Expo)$/m,
          '$1\nimport FirebaseCore'
        );
      }

      // 2. Insertar FirebaseApp.configure() antes del return de super.application
      const anchor = 'return super.application(application, didFinishLaunchingWithOptions: launchOptions)';
      if (contents.includes(anchor) && !contents.includes('FirebaseApp.configure()')) {
        contents = contents.replace(
          anchor,
          '    // @generated by withFirebaseAppDelegate\n    FirebaseApp.configure()\n    ' + anchor
        );
        console.log('[withFirebaseAppDelegate] FirebaseApp.configure() insertado ✅');
      } else if (contents.includes('FirebaseApp.configure()')) {
        console.log('[withFirebaseAppDelegate] FirebaseApp.configure() ya presente ✅');
      } else {
        console.warn('[withFirebaseAppDelegate] ⚠️ Ancla no encontrada — verificar AppDelegate.swift manualmente');
      }

      config.modResults.contents = contents;
    }
    return config;
  });
};

module.exports = withFirebaseAppDelegate;
